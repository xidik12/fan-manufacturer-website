// ── Language Switcher ──
(function() {
  const STORAGE_KEY = 'dongil_lang';

  function getCurrentLang() {
    return localStorage.getItem(STORAGE_KEY) || 'en';
  }

  function setLang(lang) {
    localStorage.setItem(STORAGE_KEY, lang);
    applyTranslations(lang);
    updateLangButtons(lang);
  }

  function applyTranslations(lang) {
    const t = TRANSLATIONS[lang];
    if (!t) return;

    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key]) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          el.placeholder = t[key];
        } else {
          el.textContent = t[key];
        }
      }
    });

    // Update html lang attribute
    document.documentElement.lang = lang === 'ko' ? 'ko' : 'en';
  }

  function updateLangButtons(lang) {
    document.querySelectorAll('.lang-btn').forEach(btn => {
      const btnLang = btn.getAttribute('data-lang');
      if (btnLang === lang) {
        btn.classList.add('bg-white/25', 'text-white', 'border-white/40');
        btn.classList.remove('opacity-50', 'border-white/10');
      } else {
        btn.classList.remove('bg-white/25', 'text-white', 'border-white/40');
        btn.classList.add('opacity-50', 'border-white/10');
      }
    });
  }

  // Expose globally
  window.switchLang = setLang;

  // Apply on page load, then reveal
  document.addEventListener('DOMContentLoaded', () => {
    const lang = getCurrentLang();
    applyTranslations(lang);
    updateLangButtons(lang);
    // Remove the i18n-loading style injected in <head>
    var ls = document.getElementById('i18n-hide');
    if (ls) ls.remove();
  });
})();
